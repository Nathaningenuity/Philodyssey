// Builds data/cards.js: one philosopher card per thinker, the ways to earn it, and its rarity.
// A card is earned only by doing something with that thinker:
//   isl   chart a Voyage island they appear on        arg   accept one of their arguments in a Debate
//   book  mark one of their books as read in Works    deck  finish a lecture deck that features them
//   hold  hold a view they hold in My Positions        quiz  pick them correctly in the Quiz
//   page  win the one-question challenge on their thinker page (every card has this)
// Rarity counts the ways other than the page challenge: the fewer there are, the rarer the card.
// Run: node tools/build-cards.js
const fs = require("fs"), path = require("path"), vm = require("vm"), R = path.join(__dirname, "..");
global.window = {};
const html = fs.readFileSync(path.join(R, "index.html"), "utf8");
for (const m of html.matchAll(/<script>([\s\S]*?)<\/script>/g)) if (/window\.ATLAS_(THINKERS_[A-E]|PEOPLE_EXTRA|EXTRAS) = /.test(m[1].slice(0, 4000))) { try { vm.runInThisContext(m[1]); } catch (e) {} }
["atlas-voyage", "atlas-agora", "atlas-works", "decks/index", "atlas-logbook"].forEach(f => require(path.join(R, "data", f + ".js")));
const W = window, T = [].concat(W.ATLAS_THINKERS_A || [], W.ATLAS_THINKERS_B || [], W.ATLAS_THINKERS_C || [], W.ATLAS_THINKERS_D || [], W.ATLAS_THINKERS_E || [], W.ATLAS_PEOPLE_EXTRA || []);
const C = {}; T.forEach(t => { if (!C[t.id]) C[t.id] = { isl: [], arg: [], book: [], deck: [], hold: [], quiz: 0 }; });
const add = (id, k, v) => { if (C[id] && !C[id][k].includes(v)) C[id][k].push(v); };
Object.values(W.ATLAS_VOYAGE.islands).forEach(I => (I.cast || []).forEach(c => add(c.id, "isl", I.id)));
W.ATLAS_AGORA.cards.forEach(c => add(c.author, "arg", c.id));
(W.ATLAS_WORKS || []).forEach(w => add(w.author, "book", w.id));
W.ATLAS_DECK_INDEX.forEach(d => (d.thinkers || []).forEach(t => add(t, "deck", d.id)));
const qa = new Set(((W.ATLAS_EXTRAS || {}).quiz || []).map(q => q.answer));
T.forEach(t => { if (C[t.id] && (qa.has(t.id) || (t.positions && Object.keys(t.positions).length >= 3))) C[t.id].quiz = 1; });
// My Positions: a question's option names a position; the position lists its holders
const LB = W.ATLAS_LOGBOOK, P = LB.positions || {}, Q = [].concat(...Object.values(LB.questions || {}).map(x => Array.isArray(x) ? x : [x]));
const holdKeys = {};
(Array.isArray(LB.questions) ? LB.questions : Q).forEach(q => (q.options || []).forEach(o => { const pos = o.pos && P[o.pos]; (pos && pos.holders || []).forEach(h => { if (C[h]) { add(h, "hold", q.id + "|" + (o.key || o.id)); } }); }));
const ways = id => { const c = C[id]; return c.isl.length + c.arg.length + c.book.length + c.deck.length + c.hold.length + c.quiz; };
const tier = n => n <= 1 ? "legendary" : n === 2 ? "epic" : n <= 4 ? "rare" : n <= 7 ? "uncommon" : "common";
const out = {}; Object.keys(C).forEach(id => { out[id] = Object.assign({ r: tier(ways(id)) }, C[id]); });
const hist = {}; Object.values(out).forEach(c => { hist[c.r] = (hist[c.r] || 0) + 1; });
fs.writeFileSync(path.join(R, "data/cards.js"), "// generated by tools/build-cards.js\nwindow.ATLAS_CARDS = " + JSON.stringify(out) + ";\n");
console.log(Object.keys(out).length + " cards", JSON.stringify(hist));
