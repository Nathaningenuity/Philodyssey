// Builds data/atlas-links.js: a small index so the Compass knows, without loading the 8 MB notebook,
// which My Positions question each Compass question feeds, and how many defences it offers.
// Run after editing data/atlas-logbook.js:  node tools/build-links.js
const fs = require("fs"), path = require("path"), root = path.join(__dirname, "..");
global.window = {}; require(path.join(root, "data/atlas-logbook.js"));
const L = window.ATLAS_LOGBOOK, tabs = {}; L.tabs.forEach(t => { tabs[t.id] = t.name; });
const cq = {};
Object.values(L.questions).forEach(q => { if (!q.compass || cq[q.compass.q]) return;
  cq[q.compass.q] = { n: q.id, tab: q.tab, tn: tabs[q.tab] || q.tab, ch: (q.challenges || []).length, rs: (q.reasons || []).length }; });
fs.writeFileSync(path.join(root, "data/atlas-links.js"), "// generated by tools/build-links.js; do not edit by hand\nwindow.ATLAS_LINKS = " + JSON.stringify({ cq }) + ";\n");
console.log("linked compass questions:", Object.keys(cq).length);
