// Bundles the Voyage's own pictures, img/voy/u<N>/*.webp, into data/voyimg/u<N>.js (one file per sea, loaded when an island in that sea opens).
// It also checks that every img/voy/ picture the Voyage names exists, and lists pictures nothing uses.
// Run: node tools/build-voyimg.js
const fs = require("fs"), path = require("path"), R = path.join(__dirname, "..");
global.window = {}; require(path.join(R, "data/atlas-voyage.js"));
const used = new Set(), errs = [];
Object.values(window.ATLAS_VOYAGE.islands).forEach(I => (I.slides || []).forEach((s, i) => [s.img, s.a && s.a.img, s.b && s.b.img].concat((s.items || []).map(c => c && c.img)).forEach(im => {
  const f = im && im.file; if (!f || !/^img\/voy\//.test(f)) return; used.add(f);
  if (!fs.existsSync(path.join(R, f))) errs.push(I.id + " slide " + i + ": missing " + f);
  if (!/^img\/voy\/u\d+\//.test(f)) errs.push(I.id + " slide " + i + ": not in a sea folder " + f);
})));
const base = path.join(R, "img/voy"), out = path.join(R, "data/voyimg"); fs.mkdirSync(out, { recursive: true });
const report = [];
for (const u of fs.readdirSync(base).filter(d => /^u\d+$/.test(d))) {
  const M = {}; let n = 0, bytes = 0;
  for (const f of fs.readdirSync(path.join(base, u)).filter(f => f.endsWith(".webp")).sort()) {
    const rel = "img/voy/" + u + "/" + f; if (!used.has(rel)) { errs.push("unused " + rel); continue; }
    const b = fs.readFileSync(path.join(base, u, f)); M[rel] = "data:image/webp;base64," + b.toString("base64"); n++; bytes += b.length;
  }
  fs.writeFileSync(path.join(out, u + ".js"), "// generated by tools/build-voyimg.js\nwindow.ATLAS_VOYIMG = Object.assign(window.ATLAS_VOYIMG || {}, " + JSON.stringify(M) + ");\n");
  report.push(u + ": " + n + " pictures, " + Math.round(bytes / 1024) + " KB");
}
console.log(report.join("\n")); if (errs.length) { console.log(errs.join("\n")); process.exitCode = 1; }
